    PROPOSED = "PROPOSED"
    VALIDATING = "VALIDATING"
    READY = "READY"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPLIED = "APPLIED"
    REJECTED = "REJECTED"
    CONFLICT = "CONFLICT"
